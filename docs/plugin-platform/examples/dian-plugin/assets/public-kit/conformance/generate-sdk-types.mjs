// Generates examples/sdk/host-api.d.ts: TypeScript types for every schema and a
// route map so ctx.api.get/post/... infer request bodies and responses by path.
//   node generate-sdk-types.mjs          write
//   node generate-sdk-types.mjs --check  fail when the file is stale
import { readFileSync, writeFileSync } from 'node:fs'
import { root, doc, operations, resolve, jsonContent, successResponse, parameters } from './openapi-model.mjs'

const typeName = name => name.replace(/[^A-Za-z0-9_]/g, '_').replace(/^[0-9]/, '_$&')
const propKey = key => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
const comment = (text, indent) => text ? `${indent}/** ${String(text).replaceAll('*/', '* /').replaceAll('\n', ' ')} */\n` : ''

function ts(schema, indent = '') {
  if (!schema || typeof schema !== 'object') return 'unknown'
  if (schema.$ref) return typeName(schema.$ref.split('/').pop())
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ')
  const branches = schema.oneOf || schema.anyOf
  if (branches && branches.some(b => b.$ref || b.type || b.properties)) {
    const base = { ...schema }; delete base.oneOf; delete base.anyOf
    const union = branches.map(b => ts(b, indent)).join(' | ')
    return Object.keys(base).length > 0 && (base.type || base.properties) ? `(${ts(base, indent)}) & (${union})` : union
  }
  if (schema.allOf) return schema.allOf.map(s => ts(s, indent)).join(' & ')
  const types = Array.isArray(schema.type) ? schema.type : [schema.type || (schema.properties ? 'object' : schema.items ? 'array' : '')]
  const parts = types.map(type => {
    switch (type) {
      case 'string': return 'string'
      case 'integer': case 'number': return 'number'
      case 'boolean': return 'boolean'
      case 'null': return 'null'
      case 'array': return `Array<${ts(schema.items, indent)}>`
      case 'object': {
        const required = new Set(schema.required || [])
        const inner = indent + '  '
        const lines = Object.entries(schema.properties || {}).map(([k, v]) =>
          comment(v.description, inner) + `${inner}${propKey(k)}${required.has(k) ? '' : '?'}: ${ts(v, inner)}`)
        const extra = schema.additionalProperties
        if (extra && extra !== false) lines.push(`${inner}[key: string]: ${typeof extra === 'object' && Object.keys(extra).length && !schema.properties ? ts(extra, inner) : 'unknown'}`)
        if (!lines.length) return 'Record<string, unknown>'
        return `{\n${lines.join('\n')}\n${indent}}`
      }
    }
    return 'unknown'
  })
  return parts.join(' | ')
}

const out = [
  '// Generated by docs/plugin-platform/conformance/generate-sdk-types.mjs from openapi-v3.json. Do not edit.',
  '/* eslint-disable */',
  '',
]
for (const [name, schema] of Object.entries(doc.components.schemas)) {
  out.push(comment(schema.description, '') + `export type ${typeName(name)} = ${ts(schema)}`, '')
}
const routes = []
for (const { path, method, op } of operations()) {
  if (!path.startsWith('/api/')) continue
  const query = parameters(op).filter(p => p.in === 'query')
  const queryType = query.length ? `{ ${query.map(p => `${propKey(p.name)}${p.required ? '' : '?'}: ${ts(p.schema)}`).join('; ')} }` : 'never'
  const body = jsonContent(op.requestBody)
  const ok = successResponse(op)
  const content = ok && jsonContent(ok.response)
  routes.push(comment(op.summary + (op.description ? '。' + op.description : ''), '  ') +
    `  ${JSON.stringify(method.toUpperCase() + ' ' + path)}: { query: ${queryType}; body: ${body ? ts(body.schema, '    ') : 'never'}; response: ${content ? ts(content.schema, '    ') : 'unknown'} }`)
}
out.push('/** Every public host route: "METHOD /api/path/{param}" -> query, JSON body and success response. */',
  'export interface HostRoutes {', ...routes, '}', '',
  `type Method = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'HEAD'
type Pattern<S extends string> = S extends \`\${infer A}{\${string}}\${infer B}\` ? \`\${A}\${string}\${Pattern<B>}\` : S
type RoutesOf<M extends Method> = { [K in keyof HostRoutes as K extends \`\${M} \${infer P}\` ? P : never]: HostRoutes[K] }
type Exact<M extends Method, P extends string> = P extends keyof RoutesOf<M> ? P : P extends \`\${infer Base}?\${string}\` ? (Base extends keyof RoutesOf<M> ? Base : never) : never
type Loose<M extends Method, P extends string> = { [K in keyof RoutesOf<M> & string]: P extends Pattern<K> | \`\${Pattern<K>}?\${string}\` ? K : never }[keyof RoutesOf<M> & string]
/** The documented route a literal path resolves to (exact match first, then {param} patterns). */
export type RouteOf<M extends Method, P extends string> = string extends P ? never : [Exact<M, P>] extends [never] ? Loose<M, P> : Exact<M, P>
type Pick1<R, F extends string> = R extends Record<F, infer V> ? V : unknown
type Field<M extends Method, P extends string, F extends 'body' | 'response'> = [RouteOf<M, P>] extends [never] ? unknown : RouteOf<M, P> extends infer K ? K extends string ? \`\${M} \${K}\` extends infer Full ? Full extends keyof HostRoutes ? Pick1<HostRoutes[Full], F> : unknown : unknown : unknown : unknown
/** Response JSON of a host route. */
export type HostResponse<M extends Method, P extends string> = Field<M, P, 'response'>
/** JSON body accepted by a host route. */
export type HostBody<M extends Method, P extends string> = Field<M, P, 'body'>

/**
 * ctx.api: calls an ordinary host /api route. Documented paths infer the body and
 * response types (query strings allowed); other paths return unknown.
 */
export interface TypedHostAPI {
  get<P extends string, T = HostResponse<'GET', P>>(path: P): Promise<T>
  head<P extends string>(path: P): Promise<unknown>
  delete<P extends string, T = HostResponse<'DELETE', P>>(path: P, body?: HostBody<'DELETE', P>): Promise<T>
  post<P extends string, T = HostResponse<'POST', P>>(path: P, body?: HostBody<'POST', P>): Promise<T>
  put<P extends string, T = HostResponse<'PUT', P>>(path: P, body?: HostBody<'PUT', P>): Promise<T>
  patch<P extends string, T = HostResponse<'PATCH', P>>(path: P, body?: HostBody<'PATCH', P>): Promise<T>
}
`)
const content = out.join('\n')
const target = new URL('examples/sdk/host-api.d.ts', root)
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch {}
  if (current !== content) throw Error('host-api.d.ts 未同步，请运行 generate-sdk-types.mjs')
  console.log(`SDK 宿主接口类型一致：${routes.length} 个路由`)
} else {
  writeFileSync(target, content)
  console.log(`已生成 SDK 宿主接口类型：${routes.length} 个路由、${Object.keys(doc.components.schemas).length} 个类型`)
}
